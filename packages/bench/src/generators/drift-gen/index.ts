/**
 * Bump on any change to schedule.ts / render.ts / names.ts: those changes
 * alter generated bytes for existing seeds (dataset runbook, Maintenance 1).
 */
export const DRIFT_GEN_VERSION = "1.0.0";

/**
 * Fixed sentinel so repeated runs with the same seed are byte-identical
 * (dataset convention 4 forbids wall-clock timestamps in generated files).
 */
const MANIFEST_TIMESTAMP = "1970-01-01T00:00:00.000Z";

export const DRIFT_GEN_DEFAULTS = Object.freeze({
  users: 5,
  epochs: 12,
  seed: 11,
  factsPerEpoch: 8,
  driftingRatio: 0.2,
  contradictedRatio: 0.1,
});

export function buildDriftCorpus(
  options: Omit<DriftGenOptions, "outDir">,
): DriftGenCorpus {
  const factsPerEpoch = options.factsPerEpoch ?? DRIFT_GEN_DEFAULTS.factsPerEpoch;
  const driftingRatio = options.driftingRatio ?? DRIFT_GEN_DEFAULTS.driftingRatio;
  const contradictedRatio =
    options.contradictedRatio ?? DRIFT_GEN_DEFAULTS.contradictedRatio;
  const schedule = buildCorpusSchedule({
    users: options.users,
    epochs: options.epochs,
    seed: options.seed,
    factsPerEpoch,
    driftingRatio,
    contradictedRatio,
  });
  const renderRng = createSeededRandom((options.seed ^ 0x5f3759) >>> 0);
  const sessions: DriftSession[] = [];
  for (const user of schedule.users) {
    sessions.push(...renderUserSessions(renderRng, user, options.epochs));
  }
  return { facts: schedule.facts, probes: schedule.probes, sessions };
}

function toJsonl(rows: readonly unknown[]): string {
  return `${rows.map((row) => JSON.stringify(row)).join("\n")}\n`;
}

export async function generateDriftCorpus(
  options: DriftGenOptions,
): Promise<DriftGenResult> {
  const corpus = buildDriftCorpus(options);
  const seedDir = String(options.seed);
  const written = new Map<string, string>();

  written.set(
    path.join(seedDir, "gold", "facts.jsonl"),
    toJsonl(corpus.facts),
  );
  written.set(
    path.join(seedDir, "gold", "probes.jsonl"),
    toJsonl(corpus.probes),
  );
  const sessionsByUser = new Map<string, DriftSession[]>();
  for (const session of corpus.sessions) {
    const list = sessionsByUser.get(session.userId) ?? [];
    list.push(session);
    sessionsByUser.set(session.userId, list);
  }
  for (const [userId, sessions] of [...sessionsByUser.entries()].sort()) {
    written.set(
      path.join(seedDir, "users", userId, "sessions.jsonl"),
      toJsonl(sessions),
    );
  }

  const files: Record<string, string> = {};
  for (const relPath of [...written.keys()].sort()) {
    files[relPath] = createHash("sha256")
      .update(written.get(relPath) as string)
      .digest("hex");
  }

  const manifest: DriftGenManifest = {
    name: "drift-gen-core",
    version: DRIFT_GEN_VERSION,
    generatorVersion: DRIFT_GEN_VERSION,
    seeds: [options.seed],
    counts: {
      users: options.users,
      epochs: options.epochs,
      facts: corpus.facts.length,
      probes: corpus.probes.length,
    },
    generator: {
      factsPerEpoch: options.factsPerEpoch ?? DRIFT_GEN_DEFAULTS.factsPerEpoch,
      driftingRatio: options.driftingRatio ?? DRIFT_GEN_DEFAULTS.driftingRatio,
      contradictedRatio:
        options.contradictedRatio ?? DRIFT_GEN_DEFAULTS.contradictedRatio,
    },
    files,
    createdAt: MANIFEST_TIMESTAMP,
    licenses: [{ source: "synthetic", license: "MIT (repo)" }],
    ...(options.audit ? { audit: options.audit } : {}),
  };

  // Stage the seed tree, swap it into place, and only then discard the old
  // corpus: the previous version is renamed aside (not deleted) until the
  // replacement is committed, and a failed swap rolls it back. The manifest
  // is replaced last via atomic rename: it is the success marker and must
  // never point at half-written data.
  const stagingDir = path.join(options.outDir, `.staging-${options.seed}`);
  await rm(stagingDir, { recursive: true, force: true });
  for (const [relPath, content] of written) {
    const absPath = path.join(stagingDir, path.relative(seedDir, relPath));
    await mkdir(path.dirname(absPath), { recursive: true });
    await writeFile(absPath, content, "utf8");
  }
  const finalSeedDir = path.join(options.outDir, seedDir);
  const backupDir = path.join(options.outDir, `.backup-${options.seed}`);
  await rm(backupDir, { recursive: true, force: true });
  let hadPrevious = true;
  try {
    await rename(finalSeedDir, backupDir);
  } catch {
    hadPrevious = false;
  }
  try {
    await rename(stagingDir, finalSeedDir);
    const manifestPath = path.join(options.outDir, "dataset.manifest.json");
    const manifestStaging = path.join(options.outDir, ".staging-manifest.json");
    await writeFile(manifestStaging, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
    await rename(manifestStaging, manifestPath);
  } catch (err) {
    await rm(finalSeedDir, { recursive: true, force: true });
    if (hadPrevious) {
      try {
        await rename(backupDir, finalSeedDir);
      } catch {
        console.error(
          `drift-gen: failed to restore the previous corpus; it is preserved at ${backupDir}`,
        );
      }
    }
    throw err;
  }
  if (hadPrevious) {
    await rm(backupDir, { recursive: true, force: true });
  }

  // A regenerated corpus owns its output dir: seed trees absent from the
  // replacement manifest are stale leftovers from earlier runs and would be
  // ingested by consumers that enumerate the directory. Only all-digit
  // directory names are generator-owned and eligible for removal.
  const staleEntries = await readdir(options.outDir, { withFileTypes: true });
  for (const entry of staleEntries) {
    if (!entry.isDirectory() || !/^\d+$/.test(entry.name)) continue;
    if (entry.name === seedDir) continue;
    await rm(path.join(options.outDir, entry.name), { recursive: true, force: true });
  }

  return { manifest, files: [...written.keys()].sort() };
}

function renderValidationReport(report: DriftValidationReport): string {
  const lines: string[] = [];
  lines.push(report.ok ? "drift-gen corpus: VALID" : "drift-gen corpus: INVALID");
  const { stats } = report;
  lines.push(
    `  facts=${stats.facts} probes=${stats.probes} sessions=${stats.sessions} users=${stats.users} epochs=${stats.epochs}`,
  );
  lines.push(
    `  factsPerEpochMean=${stats.factsPerEpochMean.toFixed(2)} drifting=${stats.driftingRatio.toFixed(3)} contradicted=${stats.contradictedRatio.toFixed(3)}`,
  );
  lines.push(
    `  probes by category: current=${stats.probesByCategory.current} historical=${stats.probesByCategory.historical} transition=${stats.probesByCategory.transition} aggregation=${stats.probesByCategory.aggregation}`,
  );
  lines.push(
    `  max question/answer leakage: ${(stats.maxQuestionAnswerLeakage * 100).toFixed(0)}%`,
  );
  for (const warning of report.warnings) lines.push(`  warning: ${warning}`);
  for (const error of report.errors) lines.push(`  error: ${error}`);
  return lines.join("\n");
}

export interface DriftGenCliOptions {
  action: "generate" | "validate";
  dir?: string;
  users?: number;
  epochs?: number;
  seed?: number;
  out?: string;
  factsPerEpoch?: number;
  driftingRatio?: number;
  contradictedRatio?: number;
  json?: boolean;
}

export async function runDriftGenCliCommand(
  options: DriftGenCliOptions,
): Promise<{ exitCode: number; output: string }> {
  if (options.action === "validate") {
    if (!options.dir) {
      return {
        exitCode: 1,
        output: "drift-gen validate requires a corpus directory: remnic bench drift-gen validate <dir>",
      };
    }
    const report = await validateDriftCorpus(options.dir);
    return {
      exitCode: report.ok ? 0 : 1,
      output: options.json
        ? JSON.stringify(report, null, 2)
        : renderValidationReport(report),
    };
  }

  if (!options.out) {
    return {
      exitCode: 1,
      output: "drift-gen requires --out <dir> to write the corpus",
    };
  }
  const result = await generateDriftCorpus({
    users: options.users ?? DRIFT_GEN_DEFAULTS.users,
    epochs: options.epochs ?? DRIFT_GEN_DEFAULTS.epochs,
    seed: options.seed ?? DRIFT_GEN_DEFAULTS.seed,
    outDir: options.out,
    factsPerEpoch: options.factsPerEpoch,
    driftingRatio: options.driftingRatio,
    contradictedRatio: options.contradictedRatio,
  });
  if (options.json) {
    return { exitCode: 0, output: JSON.stringify(result.manifest, null, 2) };
  }
  const { counts } = result.manifest;
  return {
    exitCode: 0,
    output: [
      `drift-gen v${DRIFT_GEN_VERSION}: wrote ${result.files.length + 1} files to ${options.out}`,
      `  users=${counts.users} epochs=${counts.epochs} facts=${counts.facts} probes=${counts.probes} seed=${result.manifest.seeds[0]}`,
      `  validate with: remnic bench drift-gen validate ${options.out}`,
    ].join("\n"),
  };
}

