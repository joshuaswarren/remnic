
export const REVIEW_DEDUP_CONFIG = Object.freeze({
  shingleSize: 1,
  similarityThreshold: 0.5,
  directionalSetMin: 0.9,
  directionalOrderMax: 0.1,
  polarityContentSim: 0.7,
});

